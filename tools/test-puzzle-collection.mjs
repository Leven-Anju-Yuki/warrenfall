import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('assets/js/script.js','utf8');
const catalog=JSON.parse(fs.readFileSync('lapinous-puzzles.json','utf8')).puzzles;
const game={ownedSpecies:['azur','myco']},progress={unlockedPuzzle:0,puzzles:{}};
let active=[],received;
const coloring={};
const window={getPuzzleCatalog:()=>catalog,LapinousVisibility:{allowed:()=>true},LapinousColoring:{open:args=>{received=args.catalog;}}};
const ctx=vm.createContext({window,game,isLocalAdmin:false,adminTesting:false,currentActiveEvents:()=>active,ensureMinigameProgress:()=>({puzzle:progress,coloring}),puzzleState:()=>({completed:false}),getSpecies:()=>({azur:{faceImg:'azur.png'},myco:{faceImg:'myco.png'}}),rabbitDisplayName:({key})=>key,gameArea:{},autoSave(){}});
vm.runInContext(source.slice(source.indexOf('        function puzzleCatalog()'),source.indexOf('        let activePuzzle =')),ctx);
const evaluate=code=>vm.runInContext(code,ctx);
assert.equal(evaluate(`isPuzzleUnlocked(${catalog.findIndex(p=>p.id==='nature')})`),true,'Myco unlocks the forest without solving unrelated puzzles');
assert.equal(evaluate(`isPuzzleUnlocked(${catalog.findIndex(p=>p.id==='scientifiques')})`),false);
assert.equal(evaluate("puzzleCollectionAccess(puzzleCatalog().find(p=>p.id==='communs'))"),true);
game.ownedSpecies.push('jackFrost');
assert.equal(evaluate(`isPuzzleUnlocked(${catalog.findIndex(p=>p.id==='noel')})`),false,'Event restriction retained');
game.ownedSpecies.pop();
const start=source.indexOf('        window.openColoring = function ()');
vm.runInContext(source.slice(start,source.indexOf('        window.openGameConsole =',start)),ctx);
window.openColoring();
assert.deepEqual(Array.from(received.filter(p=>p.kind==='scene'),p=>p.id).sort(),['communs','nature']);
coloring['scientifiques:1:v3']={painted:[1,0,0]};
const before=JSON.stringify(coloring);
window.openColoring();
assert.equal(received.some(p=>p.id==='scientifiques'),true,'Started old coloring remains accessible');
assert.equal(JSON.stringify(coloring),before,'No progress rewritten');
console.log('Azur + Myco: matching puzzle and coloring groups, seasonal locks and old coloring progress OK');
