import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const files=new Map([['admin.json','manual untouched']]);
let allowed=true,failWrite=false;
const handle=name=>({kind:'file',getFile:async()=>({text:async()=>files.get(name)}),createWritable:async()=>{let pending;return {write:async text=>{if(failWrite)throw Error('disk full');pending=text;},close:async()=>files.set(name,pending),abort:async()=>{}};}});
const folder={name:'Lapinous sauvegarde',queryPermission:async()=>allowed?'granted':'denied',getFileHandle:async name=>handle(name),async *entries(){for(const name of [...files.keys()])yield [name,handle(name)];},removeEntry:async name=>files.delete(name)};
const context={window:{showDirectoryPicker:async()=>folder},document:{addEventListener(){}},indexedDB:{open(){throw Error('No database in fixture');}}};
vm.createContext(context);vm.runInContext(fs.readFileSync('assets/js/local-files.js','utf8'),context);
const api=context.window.LapinousLocalFiles;
assert.equal(await api.writeAutoNests([]),false);
await api.chooseSaves();
for(let n=0;n<5;n++)assert.equal(await api.writeAutoNests(Array.from({length:3},(_,i)=>({name:'Petit nid',savedAt:n*100+i,data:{carrots:n-i,inventory:{mint:10}}}))),true);
assert.equal(files.size,4);assert.equal(files.get('admin.json'),'manual untouched');
const names=[...files.keys()].filter(n=>n!=='admin.json').sort();
assert.ok(names.every(n=>/^warrenfall-petit-nid-auto-[123]-\d{2}-\d{2}-\d{4}_\d{2}h\d{2}-\d{2}-\d{3}\.json$/.test(n)));
assert.equal(JSON.parse(files.get(names[0])).carrots,4);
assert.equal(JSON.parse(files.get(names[2])).autoNest.savedAt,402);
assert.equal(JSON.parse(files.get(names[0])).autoNest.savedAtISO,new Date(400).toISOString());
const intact=JSON.stringify([...files]);failWrite=true;await assert.rejects(api.writeAutoNests([{name:'Nid',savedAt:999,data:{carrots:99}}]));assert.equal(JSON.stringify([...files]),intact);failWrite=false;
files.set('warrenfall-petit-nid-auto-1.json',JSON.stringify({autoNest:{name:'Ancien nid',savedAt:1},carrots:1}));
await api.writeAutoNests([{name:'Nid',savedAt:1000,data:{carrots:10}}]);assert.equal(files.size,2);assert.equal(files.get('admin.json'),'manual untouched');
allowed=false;const before=JSON.stringify([...files]);assert.equal(await api.writeAutoNests([{data:{}}]),false);assert.equal(JSON.stringify([...files]),before);
console.log('Autosaves disque : rotation, dates, fichiers manuels et permissions OK.');
